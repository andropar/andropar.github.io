import { writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const outputPath = path.join(root, 'src/data/personal-cat-ascii.ts');
const frameUrls = Array.from({ length: 8 }, (_, index) =>
  `https://raw.githubusercontent.com/ts-animal/ts-animal/main/src/zoo/cat-coffee/frame_${index + 1}.txt`,
);
const delays = [180, 180, 180, 420, 180, 420, 180, 420];

const frames = [];
for (const url of frameUrls) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`Could not download ASCII cat frame: ${response.status} ${response.statusText}`);
  }

  frames.push((await response.text()).replace(/\r\n/g, '\n').trimEnd());
}

const moduleBody = `// Generated by scripts/generate-ascii-cat.mjs.
// Source: https://github.com/ts-animal/ts-animal/tree/main/src/zoo/cat-coffee
// License: MIT. Copyright (c) 2024 ts-animal.
export const personalCatAsciiFrames = ${JSON.stringify(frames, null, 2)} as const;

export const personalCatAsciiDelays = ${JSON.stringify(delays)} as const;
`;

await writeFile(outputPath, moduleBody);
console.log(`Generated ${frames.length} ASCII cat frame(s) at ${path.relative(root, outputPath)}.`);
